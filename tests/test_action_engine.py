def test_load_count_and_unique():
    acts = load_actions()
    assert len(acts) == 100, f"动作数量应为 100，实际 {len(acts)}"
    ids = [a["id"] for a in acts]
    assert len(ids) == len(set(ids)), "存在重复动作 id"
    print("PASS: test_load_count_and_unique =", len(acts))


def test_neutral_clean():
    """中性站姿只应命中静止姿态，不得出现摸头/低头/蹲下等误报。"""
    got = detect()
    assert set(got) == {"stand_up", "arms_down"}, got
    print("PASS: test_neutral_clean ->", got)


def test_sample_detectable():
    """代表性动作（核心 + 扩展）都能被检出。"""
    for name, spec in SAMPLE.items():
        got = detect(spec["pose"])
        assert name in got, f"{name}: 未检出，结果 {got}"
        print(f"PASS: {name:18s} -> {got}")


def test_regression_no_cross_talk():
    """回归：抬手不得连带低头/摸头/蹲下/摸膝盖等。"""
    raise_res = detect(SAMPLE["raise_right"]["pose"])
    for bad in ("touch_head", "nod_down", "squat", "touch_knee", "touch_belly"):
        assert bad not in raise_res, f"raise_right 误报 {bad}: {raise_res}"
    squat_res = detect(SAMPLE["squat"]["pose"])
    assert "stand_up" not in squat_res and "arms_down" not in squat_res, squat_res
    print("PASS: test_regression_no_cross_talk")


